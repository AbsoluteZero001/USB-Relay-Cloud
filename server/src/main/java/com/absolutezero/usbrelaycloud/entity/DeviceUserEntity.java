package com.absolutezero.usbrelaycloud.entity;

import com.absolutezero.usbrelaycloud.common.enums.DeviceRole;
import com.baomidou.mybatisplus.annotation.IdType;
import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableName;

import java.time.Instant;

@TableName("device_user")
public class DeviceUserEntity {

    @TableId(type = IdType.AUTO)
    private Long id;
    private Long userId;
    private String deviceId;
    private DeviceRole role;
    private Instant createdAt;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getUserId() {
        return userId;
    }

    public void setUserId(Long userId) {
        this.userId = userId;
    }

    public String getDeviceId() {
        return deviceId;
    }

    public void setDeviceId(String deviceId) {
        this.deviceId = deviceId;
    }

    public DeviceRole getRole() {
        return role;
    }

    public void setRole(DeviceRole role) {
        this.role = role;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }
}
